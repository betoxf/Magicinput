pub const HID_ESCAPE: u16 = 0x29;
pub const HID_CAPS_LOCK: u16 = 0x39;
pub const HID_PAUSE: u16 = 0x48;

pub fn hid_from_mac(code: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.1 == code).map(|e| e.0)
}

pub fn mac_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.0 == hid && e.1 != NONE).map(|e| e.1)
}

pub fn hid_from_win(scan: u16) -> Option<u16> {
    let find = |sc: u16| TABLE.iter().find(|e| e.2 == sc).map(|e| e.0);
    // Some keys (e.g. right shift) are reported with the extended flag even though they aren't.
    find(scan).or_else(|| find(scan & 0xFF))
}

pub fn win_from_hid(hid: u16) -> Option<u16> {
    TABLE.iter().find(|e| e.0 == hid && e.2 != NONE).map(|e| e.2)
}

pub fn is_ctrl(hid: u16) -> bool {
    hid == 0xE0 || hid == 0xE4
}
pub fn is_alt(hid: u16) -> bool {
    hid == 0xE2 || hid == 0xE6
}

/// Swap Ctrl <-> Cmd/Win so Mac-style shortcuts (Cmd+C) do the native thing on Windows and vice versa.
pub fn swap_ctrl_gui(hid: u16) -> u16 {
    match hid {
        0xE0 => 0xE3,
        0xE3 => 0xE0,
        0xE4 => 0xE7,
        0xE7 => 0xE4,
        h => h,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_unambiguous() {
        for (i, a) in TABLE.iter().enumerate() {
            for b in &TABLE[i + 1..] {
                assert_ne!(a.0, b.0, "dup hid {:#x}", a.0);
                if a.1 != NONE {
                    assert_ne!(a.1, b.1, "dup mac {:#x}", a.1);
                }
                if a.2 != NONE {
                    assert_ne!(a.2, b.2, "dup win {:#x}", a.2);
                }
            }
        }
    }

    #[test]
    fn mac_to_windows() {
        // Cmd+C on a Mac keyboard becomes Ctrl+C on Windows.
        let cmd = hid_from_mac(0x37).unwrap();
        assert_eq!(win_from_hid(swap_ctrl_gui(cmd)), Some(0x1D));
        assert_eq!(win_from_hid(hid_from_mac(0x08).unwrap()), Some(0x2E)); // c
        assert_eq!(win_from_hid(hid_from_mac(0x7B).unwrap()), Some(0xE04B)); // left arrow
    }

    #[test]
    fn windows_to_mac() {
        assert_eq!(mac_from_hid(hid_from_win(0x1E).unwrap()), Some(0x00)); // a
        assert_eq!(hid_from_win(0xE036), Some(0xE5)); // right shift reported as extended
        assert_eq!(mac_from_hid(hid_from_win(0xE05B).unwrap()), Some(0x37)); // win -> cmd
    }
}
